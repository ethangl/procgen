/// Camera distance at or below which adjusted elevation uses GPU terrain tiles.
const TERRAIN_TILE_ZOOM_THRESHOLD: f32 = 1.75;
const TERRAIN_MAX_TILE_LEVEL: u8 = 12;

/// Next power-of-two capacity above the measured 982-tile close-view handoff demand.
const MAX_RESIDENT_TILES: usize = 1_024;
/// Maximum number of new terrain tiles generated by the viewer in one frame.
const NEW_TERRAIN_TILES_PER_FRAME: usize = 8;
/// Radial skirt depth in units of the tile's nominal vertex spacing.
const TERRAIN_SKIRT_DEPTH_SPACINGS: f32 = 2.0;
const TERRAIN_SAMPLE_CAPACITY: usize = MAX_RESIDENT_TILES * TERRAIN_TILE_SAMPLE_COUNT;
const TERRAIN_SLOT_BITS: u32 = MAX_RESIDENT_TILES.trailing_zeros();
const TERRAIN_SLOT_MASK: u32 = MAX_RESIDENT_TILES as u32 - 1;
const TERRAIN_MORPH_BITS: u32 = u32::BITS - 2 * TERRAIN_SLOT_BITS;
const TERRAIN_MORPH_MAX: u32 = (1 << TERRAIN_MORPH_BITS) - 1;

const _: () = assert!(MAX_RESIDENT_TILES.is_power_of_two());

const TERRAIN_VERTEX_SHADER: Handle<Shader> = uuid_handle!("f793fce0-ef68-49dd-8c98-7bba8432bc76");
const TERRAIN_COMPUTE_SHADER: Handle<Shader> = uuid_handle!("c7c57793-ae7c-4eb7-a1a9-9b8fb2d5a651");

