pub(super) struct TerrainTileRenderPlugin;

impl Plugin for TerrainTileRenderPlugin {
    fn build(&self, app: &mut App) {
        register_shaders(app);
        app.add_plugins((
            MaterialPlugin::<TerrainTileMaterial>::default(),
            ExtractResourcePlugin::<TerrainGpuResources>::default(),
            ExtractResourcePlugin::<TerrainTileDispatch>::default(),
        ))
        .init_resource::<TerrainTileCoverage>()
        .init_resource::<TerrainTileDispatch>()
        .init_resource::<TerrainTileMode>()
        .init_resource::<QuadtreeSelection>()
        .init_resource::<TileResidency>()
        .add_systems(Startup, initialize_grid_mesh)
        .add_systems(
            Update,
            (
                initialize_gpu_world.run_if(resource_changed::<GeneratedWorld>),
                sync_mode.run_if(resource_changed::<SurfaceSelection>.or(camera_changed)),
                sync_relief.run_if(
                    resource_changed::<ReliefSettings>.and(resource_exists::<TerrainTileAssets>),
                ),
                update_tile_coverage
                    .run_if(resource_exists::<TerrainTileAssets>)
                    .run_if(
                        resource_changed::<GeneratedWorld>
                            .or(resource_changed::<TerrainTileMode>)
                            .or(camera_changed)
                            .or(terrain_dispatch_completed),
                    ),
            )
                .chain(),
        );

        compute::install(app.sub_app_mut(RenderApp));
    }
}

fn camera_changed(camera: Single<Ref<Transform>, With<OrbitCamera>>) -> bool {
    camera.is_changed()
}

fn terrain_dispatch_completed(
    dispatch: Res<TerrainTileDispatch>,
    mut observed: Local<u32>,
) -> bool {
    let changed = dispatch.is_complete() && dispatch.generation != *observed;
    if changed {
        *observed = dispatch.generation;
    }
    changed
}

pub(super) fn sync_mode(
    camera: Single<&Transform, With<OrbitCamera>>,
    selection: Res<SurfaceSelection>,
    mut mode: ResMut<TerrainTileMode>,
) {
    mode.set_if_neq(terrain_tile_mode(
        camera.translation.length(),
        selection.selected(),
    ));
}

fn initialize_grid_mesh(mut commands: Commands, mut meshes: ResMut<Assets<Mesh>>) {
    commands.insert_resource(TerrainGridMesh(meshes.add(tile_grid_mesh())));
}

fn register_shaders(app: &mut App) {
    let vertex_constants = format!(
        "const TERRAIN_ELEVATION_PALETTE_STOP_COUNT: u32 = {ELEVATION_STOP_COUNT}u;\n\
         const TERRAIN_SKIRT_DEPTH_SPACINGS: f32 = {TERRAIN_SKIRT_DEPTH_SPACINGS};\n\
         const TERRAIN_SLOT_BITS: u32 = {TERRAIN_SLOT_BITS}u;\n\
         const TERRAIN_SLOT_MASK: u32 = {TERRAIN_SLOT_MASK}u;\n\
         const TERRAIN_MORPH_MAX: u32 = {TERRAIN_MORPH_MAX}u;"
    );
    let vertex_source = [
        MAPPING_WGSL_SOURCE.to_owned(),
        vertex_constants,
        include_str!("terrain_tiles.wgsl").to_owned(),
    ]
    .join("\n");
    let compute_source = [
        TERRAIN_WGSL_SOURCE.to_owned(),
        include_str!("terrain_compute.wgsl").to_owned(),
    ]
    .join("\n");
    let mut shaders = app.world_mut().resource_mut::<Assets<Shader>>();
    shaders
        .insert(
            TERRAIN_VERTEX_SHADER.id(),
            Shader::from_wgsl(vertex_source, "procgen-terrain-viewer.wgsl"),
        )
        .unwrap();
    shaders
        .insert(
            TERRAIN_COMPUTE_SHADER.id(),
            Shader::from_wgsl(compute_source, "procgen-terrain-compute.wgsl"),
        )
        .unwrap();
}

#[derive(SystemParam)]
struct TerrainWorldAssets<'w, 's> {
    commands: Commands<'w, 's>,
    coverage: ResMut<'w, TerrainTileCoverage>,
    buffers: ResMut<'w, Assets<ShaderStorageBuffer>>,
    materials: ResMut<'w, Assets<TerrainTileMaterial>>,
    selection: ResMut<'w, QuadtreeSelection>,
    residency: ResMut<'w, TileResidency>,
    dispatch: ResMut<'w, TerrainTileDispatch>,
}

fn initialize_gpu_world(
    world: Res<GeneratedWorld>,
    relief: Res<ReliefSettings>,
    mut assets: TerrainWorldAssets,
) {
    for (_, entity) in assets.coverage.0.drain() {
        assets.commands.entity(entity).despawn();
    }
    assets.selection.clear();
    *assets.residency = TileResidency::default();
    assets.dispatch.job_count = 0;
    assets.dispatch.generation = assets.dispatch.generation.wrapping_add(1);

    // Detailed tiles read the geology phase's baked terrain controls, so
    // dropping geology drops the buffers and material built from it.
    let (Some(tectonics), Some(geology)) = (world.tectonics(), world.geology()) else {
        assets.commands.remove_resource::<TerrainGpuResources>();
        assets.commands.remove_resource::<TerrainTileAssets>();
        return;
    };
    let controls = pack_control_bake(&geology.terrain_control_bake);
    let stamps = pack_stamps(&geology.terrain_controls.stamps);
    // The bake descends from the isostatic field, so its datum is the one the
    // detailed surface is measured against.
    let sea_level = geology.isostasy.sea_level;
    let parameters = TerrainGpuParameters::new(
        &geology.terrain_control_bake,
        &geology.terrain_controls.stamps,
        TerrainNoiseKeys::new(tectonics.config.fibonacci.seed),
        sea_level,
        TerrainHeightConfig::default(),
    );
    let controls = assets.buffers.add(ShaderStorageBuffer::new(
        bytemuck::cast_slice(&controls),
        RenderAssetUsages::default(),
    ));
    let stamps = assets.buffers.add(ShaderStorageBuffer::new(
        bytemuck::cast_slice(&stamps),
        RenderAssetUsages::default(),
    ));
    let parameters = assets.buffers.add(ShaderStorageBuffer::new(
        bytemuck::bytes_of(&parameters),
        RenderAssetUsages::default(),
    ));
    // wgpu storage bindings cannot be empty; this placeholder is never dispatched.
    let jobs = assets.buffers.add(ShaderStorageBuffer::new(
        bytemuck::bytes_of(&TerrainTileJob {
            address: [0; 4],
            destination: [0; 4],
        }),
        RenderAssetUsages::default(),
    ));
    let addresses = assets.buffers.add(ShaderStorageBuffer::with_size(
        MAX_RESIDENT_TILES * size_of::<[u32; 4]>(),
        RenderAssetUsages::default(),
    ));
    let samples = assets.buffers.add(ShaderStorageBuffer::with_size(
        TERRAIN_SAMPLE_CAPACITY * size_of::<Vec4>(),
        RenderAssetUsages::default(),
    ));
    let material = assets.materials.add(ExtendedMaterial {
        base: StandardMaterial {
            base_color: Color::WHITE,
            perceptual_roughness: 1.0,
            ..default()
        },
        extension: TerrainTileExtension {
            addresses: addresses.clone(),
            samples: samples.clone(),
            display: TerrainDisplayParameters {
                relief_exaggeration: relief.exaggeration,
                surface_radius: SURFACE_RADIUS,
                padding: Vec2::ZERO,
            },
            palette: elevation_palette(sea_level),
        },
    });
    assets.commands.insert_resource(TerrainGpuResources {
        controls,
        stamps,
        parameters,
        jobs,
        addresses,
        samples,
    });
    assets
        .commands
        .insert_resource(TerrainTileAssets { material });
}

fn elevation_palette(sea_level: f32) -> TerrainElevationPalette {
    let stops = elevation_color_stops(sea_level);
    TerrainElevationPalette {
        stops: stops.map(|(value, color)| Vec4::new(color.x, color.y, color.z, value)),
    }
}

#[derive(SystemParam)]
struct TerrainCoverageAssets<'w, 's> {
    commands: Commands<'w, 's>,
    grid: Res<'w, TerrainGridMesh>,
    coverage: ResMut<'w, TerrainTileCoverage>,
    selection: ResMut<'w, QuadtreeSelection>,
    residency: ResMut<'w, TileResidency>,
    dispatch: ResMut<'w, TerrainTileDispatch>,
    resources: ResMut<'w, TerrainGpuResources>,
    tile_assets: Res<'w, TerrainTileAssets>,
    buffers: ResMut<'w, Assets<ShaderStorageBuffer>>,
}

fn sync_relief(
    relief: Res<ReliefSettings>,
    tile_assets: Res<TerrainTileAssets>,
    mut materials: ResMut<Assets<TerrainTileMaterial>>,
) {
    materials
        .get_mut(&tile_assets.material)
        .expect("terrain tile material must remain alive")
        .extension
        .display
        .relief_exaggeration = relief.exaggeration;
}

fn update_tile_coverage(
    camera: Single<(&Camera, &Projection, &Transform), With<OrbitCamera>>,
    mode: Res<TerrainTileMode>,
    mut assets: TerrainCoverageAssets,
) {
    if assets.dispatch.is_complete() {
        assets.residency.complete_in_flight();
    }
    if *mode == TerrainTileMode::Coarse {
        assets.selection.clear();
        let update = assets.residency.update(&[]);
        upload_generation_jobs(&update.generated, &mut assets);
        clear_displayed_tiles(&mut assets);
        return;
    }

    let (camera, projection, transform) = *camera;
    let Some(view) = CoverageView::from_camera(camera, projection, transform) else {
        return;
    };
    let targets = assets.selection.select(view);
    let update = assets.residency.update(&targets);
    upload_generation_jobs(&update.generated, &mut assets);
    sync_displayed_tiles(&update.displayed, view, &mut assets);
}

fn clear_displayed_tiles(assets: &mut TerrainCoverageAssets<'_, '_>) {
    for (_, entity) in assets.coverage.0.drain() {
        assets.commands.entity(entity).despawn();
    }
}

fn upload_generation_jobs(generated: &[ResidentTile], assets: &mut TerrainCoverageAssets) {
    if generated.is_empty() {
        return;
    }
    assets.resources.jobs = assets.buffers.add(ShaderStorageBuffer::new(
        bytemuck::cast_slice(&generation_jobs(generated)),
        RenderAssetUsages::default(),
    ));
    assets.dispatch.generation = assets.dispatch.generation.wrapping_add(1);
    assets.dispatch.job_count = generated.len() as u32;
}

fn generation_jobs(generated: &[ResidentTile]) -> Vec<TerrainTileJob> {
    generated
        .iter()
        .map(|tile| TerrainTileJob {
            address: tile.address.gpu_words(),
            destination: [tile.slot, 0, 0, 0],
        })
        .collect()
}

fn sync_displayed_tiles(
    displayed: &[ResidentTile],
    view: CoverageView,
    assets: &mut TerrainCoverageAssets,
) {
    let mut previous = std::mem::take(&mut assets.coverage.0);
    let mesh = assets.grid.0.clone();
    let material = assets.tile_assets.material.clone();
    assets.coverage.0 = displayed
        .iter()
        .copied()
        .map(|tile| {
            let (parent_slot, morph) = match assets.residency.ready_parent_slot(tile) {
                Some(parent_slot) => (parent_slot, tile_morph_factor(tile.address, view)),
                // Root tiles and merge fallbacks have no ready parent to sample.
                None => (tile.slot, 1.0),
            };
            let tag = terrain_mesh_tag(tile, parent_slot, morph);
            if let Some(entity) = previous.remove(&tile) {
                assets.commands.entity(entity).insert(MeshTag(tag));
                return (tile, entity);
            }
            let entity = assets
                .commands
                .spawn((
                    Mesh3d(mesh.clone()),
                    MeshMaterial3d(material.clone()),
                    MeshTag(tag),
                    Transform::from_translation(tile_origin(tile.address)),
                    NoFrustumCulling,
                ))
                .id();
            (tile, entity)
        })
        .collect();
    for (_, entity) in previous {
        assets.commands.entity(entity).despawn();
    }
}

fn terrain_mesh_tag(tile: ResidentTile, parent_slot: u32, morph: f32) -> u32 {
    assert!(tile.slot <= TERRAIN_SLOT_MASK);
    assert!(parent_slot <= TERRAIN_SLOT_MASK);
    assert!(morph.is_finite() && (0.0..=1.0).contains(&morph));
    let quantized_morph = (morph * TERRAIN_MORPH_MAX as f32).round() as u32;
    tile.slot | (parent_slot << TERRAIN_SLOT_BITS) | (quantized_morph << (2 * TERRAIN_SLOT_BITS))
}

fn terrain_tile_mode(camera_distance: f32, selected: Option<DiagnosticLayer>) -> TerrainTileMode {
    if camera_distance <= TERRAIN_TILE_ZOOM_THRESHOLD
        && selected == Some(DiagnosticLayer::IsostaticElevation)
    {
        TerrainTileMode::Tiles
    } else {
        TerrainTileMode::Coarse
    }
}

